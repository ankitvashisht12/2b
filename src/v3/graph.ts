import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { ObjectStore, type PropertyPatch } from './store.ts';
import { contentPath, atomicWrite } from './files.ts';

const START = '<!-- 2b:connections:start -->';
const END = '<!-- 2b:connections:end -->';
const hash = (text: string) => createHash('sha256').update(text).digest('hex');
export function withoutConnections(text: string): string {
  const start = text.indexOf(START), end = text.indexOf(END);
  return start >= 0 && end >= start ? (text.slice(0, start) + text.slice(end + END.length)).trimEnd() + '\n' : text;
}

export async function publishConnections(root: string, store: ObjectStore) {
  const [objects, relationships] = await Promise.all([store.list(), store.relationships()]);
  const records = new Map(objects.map(object => [object.id, object]));
  const outgoing = new Map<string, typeof relationships>();
  for (const relationship of relationships) outgoing.set(relationship.from, [...(outgoing.get(relationship.from) || []), relationship]);
  let written = 0;
  const updates: PropertyPatch[] = [];
  for (const object of objects) {
    if (!object.path?.endsWith('.md') || object.path.startsWith('archive/') || object.type === 'tag') continue;
    const target = contentPath(root, object.path);
    if (!fs.existsSync(target) || fs.statSync(target).size > 2_000_000) continue;
    const previous = fs.readFileSync(target, 'utf8');
    const links = (outgoing.get(object.id) || []).flatMap(relationship => {
      const other = records.get(relationship.to);
      if (!other?.path?.endsWith('.md') || other.path.startsWith('archive/')) return [];
      return [`- ${relationship.kind}: [[${other.path.replace(/\.md$/i, '')}|${other.name.replace(/[\]|\n]/g, ' ')}]]`];
    });
    const authored = withoutConnections(previous).trimEnd();
    const body = links.length ? `${authored}\n\n${START}\n## Related objects\n\n${links.join('\n')}\n${END}\n` : `${authored}\n`;
    if (previous === body) continue;
    atomicWrite(target, body); written++;
    const generated = object.properties.generatedBodyHash === hash(previous);
    updates.push({ id: object.id, expectedPath: object.path, expectedProperties: { fileModifiedAt: object.properties.fileModifiedAt, generatedBodyHash: object.properties.generatedBodyHash }, properties: { fileModifiedAt: fs.statSync(target).mtime.toISOString(), ...(generated ? { generatedBodyHash: hash(body) } : {}) } });
  }
  await store.patchPropertiesMany(updates);
  // Remove only obsolete pages generated by the earlier projection format.
  const oldDirectory = path.join(root, 'connections');
  if (fs.existsSync(oldDirectory)) for (const name of fs.readdirSync(oldDirectory)) {
    const target = contentPath(root, `connections/${name}`);
    if (fs.statSync(target).isFile() && fs.readFileSync(target, 'utf8').includes('Generated from 2b relationships. Edit relationships through 2b.')) fs.unlinkSync(target);
  }
  return { written, relationships: relationships.length };
}
